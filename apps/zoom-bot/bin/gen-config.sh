#!/usr/bin/env bash
# Generate config.toml from environment variables.
#
# Reads ZOOM_CLIENT_ID, ZOOM_CLIENT_SECRET, ZOOM_JOIN_URL from the environment
# (or from a .env file if present) and writes config.toml that the C++ bot
# consumes via --config. Idempotent — overwrites config.toml every run.

set -euo pipefail

cd "$(dirname "$0")/.."

if [[ -f .env ]]; then
  # shellcheck disable=SC1091
  set -a; source .env; set +a
fi

: "${ZOOM_CLIENT_ID:?ZOOM_CLIENT_ID is not set (check .env)}"
: "${ZOOM_CLIENT_SECRET:?ZOOM_CLIENT_SECRET is not set (check .env)}"
: "${ZOOM_JOIN_URL:?ZOOM_JOIN_URL is not set (check .env)}"

cat > config.toml <<TOML
# Generated by bin/gen-config.sh — do not edit by hand.
client-id="${ZOOM_CLIENT_ID}"
client-secret="${ZOOM_CLIENT_SECRET}"
join-url="${ZOOM_JOIN_URL}"

[RawAudio]
file="out/ignored.pcm"
TOML

echo "wrote config.toml"
